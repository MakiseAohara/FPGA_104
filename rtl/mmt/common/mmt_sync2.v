//==========================================================================
//  mmt_sync2.v  —  多位两级同步器（跨时钟域的基本单元）
//--------------------------------------------------------------------------
//  用途：把一组信号从 clk_a 域搬到 clk_b 域。
//
//  ⚠️ 重要限制（必须知道，别当它是万能的）：
//    这是"按位打两拍"的**准静态信号**同步器。
//    · 适用于：① 配置类信号（写一次用很久，中途抖一下无害）
//              ② 状态类信号（对方在轮询，偶尔读到一次旧值可接受）
//    · **不适用于**：需要"整组同时一致"的数据总线（比如跨域传一个递增的计数值）。
//      那种场合必须用握手（req/ack）或异步 FIFO，否则可能刚好多拍两拍时
//      高几位已经更新、低几位还没更新，读到一个从未存在过的中间值。
//    · 本工程目前用它搬的正是①②两类信号，所以够用；但这是**bring-up 级**
//      的做法，正式版应把状态类改成"快照 + 握手"。
//
//  实现：每比特两级触发器串联，第一级可能亚稳态，第二级输出已稳定。
//==========================================================================
`timescale 1ns / 1ps

module mmt_sync2 #(
    parameter WIDTH = 1,
    parameter RESET_VAL = 0
)(
    input  wire             clk_b,      // 目标时钟域
    input  wire             rst_n_b,    // 目标域复位（低有效，异步）
    input  wire [WIDTH-1:0] d_a,        // 源域信号
    output reg  [WIDTH-1:0] q_b         // 目标域同步后
);

    reg [WIDTH-1:0] s1;

    always @(posedge clk_b or negedge rst_n_b) begin
        if (!rst_n_b) begin
            s1  <= RESET_VAL[WIDTH-1:0];
            q_b <= RESET_VAL[WIDTH-1:0];
        end else begin
            s1  <= d_a;
            q_b <= s1;
        end
    end

endmodule
