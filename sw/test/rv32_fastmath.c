/*==========================================================================
 *  rv32_fastmath.c -- 给 rv32sim 用的等价 pow 替代
 *--------------------------------------------------------------------------
 *  为什么需要它：
 *    MLX90640_API.c 里的 POW2 宏展开就是 pow(2, (double)<整数>)，
 *    全程共 16 处，**指数全是整数**（scale 值、14、18）。
 *    但 pow 返回 double，在没有 FPU 的 RV32 上要跑 libgcc 的软双精度，
 *    实测每次约 13 万周期 —— 768 个像素 × 4 次 = 3 亿周期，
 *    在解释型模拟器里根本跑不完。
 *
 *  为什么它是**等价**的，不是"近似"：
 *    对整数 n，2^n 在 double 里是精确可表示的（只要在正规数范围内），
 *    libm 的 pow(2,n) 也必须返回正确舍入的结果 = 那个精确值。
 *    这里直接按 IEEE-754 的位布局拼出 2^n（指数域 = n+1023），
 *    结果与 libm 逐位相同，且只要几十个周期。
 *
 *  ★ 只处理 pow(2, 整数)。任何其它情况都会**立刻显式失败**，
 *    而不是悄悄给个错值 —— 静默的错误值比崩溃更难查。
 *==========================================================================*/
typedef unsigned long long u64;

double pow(double base, double expo)
{
    int n;
    union { u64 u; double d; } v;

    /* 必须是 2.0 的整数次幂 */
    if (base != 2.0) goto fail;
    n = (int)expo;
    if ((double)n != expo) goto fail;
    /* 正规数范围：2^-1022 .. 2^1023 */
    if (n < -1022 || n > 1023) goto fail;

    v.u = (u64)(n + 1023) << 52;
    return v.d;

fail:
    /* 往一个非法地址写一下，让 rv32sim 立刻报 TRAP 并给出 PC，
     * 而不是返回一个看起来合理其实错误的值。 */
    *(volatile unsigned int *)0xFFFFFFF0u = 0xDEADBEEFu;
    return 0.0;
}
