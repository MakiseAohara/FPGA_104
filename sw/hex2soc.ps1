# ==========================================================================
#  hex2soc.ps1 -- convert the firmware flat binary into the 4 RAM-init files
#                 that the Efinix Sapphire SoC IP reads with $readmemb
# --------------------------------------------------------------------------
#  Usage:
#     powershell -File hex2soc.ps1                 # -> .\build\soc_ram\
#     powershell -File hex2soc.ps1 -Install        # also copy into the IP dir
#
#  ---------------------------------------------------------------------------
#  HOW THE FORMAT WAS RECOVERED (do not guess it again)
#  ---------------------------------------------------------------------------
#  The IP's generated netlist says:
#      ip\sapphire_soc\sapphire_soc.v:8076
#          reg [7:0] ram_symbol0 [0:2047];   (and _1 _2 _3)
#      :8087  $readmemb("EfxSapphireSoc..._symbol0.bin", ram_symbol0);
#      :8093  _zz_ram_port0 = {sym3, sym2, sym1, sym0};      // little endian
#      :8085  _zz_address = io_bus_cmd_payload_fragment_address >>> 2;
#
#  So: 4 byte lanes, 2048 words each = 8192 bytes = 8 KB, and
#      byte at RAM offset (4*i + N)  lives in  symbolN[i].
#
#  $readmemb means BINARY text: one word per line, each word as '0'/'1' chars.
#  Inspecting a vendor .bin confirms it: 18432 bytes / 9 per line = 2048 lines,
#  first line bytes are  31 30 30 31 30 31 31 31 0A  =  "10010111\n"
#  (MSB first, LF line ending, no CR).  Decoding those files reproduces a valid
#  RISC-V image (word0 = 0x00002197 = auipc gp,2 ...), which proves the mapping.
#
#  RAM base is 0xF9000000 (sapphire_soc.v:14084 sets the reset vector there and
#  :8315 windows it with a ~0x1FFF mask), so the binary is placed at offset 0.
# ==========================================================================
param(
    [string]$Bin     = '',
    [string]$OutDir  = '',
    [string]$IpDir   = 'D:\FPGA\mmt\ip\sapphire_soc',
    [int]   $RamBytes = 0,          # 0 = auto-detect (see below)
    [switch]$Install
)

$ErrorActionPreference = 'Continue'

$sw = $PSScriptRoot
if (-not $Bin)    { $Bin    = Join-Path $sw 'build\mmt_fw.bin' }
if (-not $OutDir) { $OutDir = Join-Path $sw 'build\soc_ram' }

$SYMS = 4

# ---------------------------------------------------------------------------
#  RAM size: auto-detect from the symbol files already in the IP directory.
#  Those files are generated by the IP manager from the SoC parameter OCRSize
#  (in BYTES) -- e.g. OCRSize=32768 -> 8192 lines per symbol -> 32 KB.  Reading
#  it back is authoritative and self-maintaining: if the SoC is regenerated
#  with a different size, this script follows automatically instead of writing
#  a file that is silently the wrong length.
# ---------------------------------------------------------------------------
$sym0 = Join-Path $IpDir 'EfxSapphireSoc.v_toplevel_system_ramA_logic_ram_symbol0.bin'
if ($RamBytes -le 0) {
    if (Test-Path $sym0) {
        $RamBytes = ([System.IO.File]::ReadAllLines($sym0)).Count * 4
        Write-Output ("RAM size  : {0} bytes (auto-detected from {1})" -f $RamBytes, $sym0)
    } else {
        $RamBytes = 8192
        Write-Output ("RAM size  : {0} bytes (fallback default; no symbol file to read)" -f $RamBytes)
    }
} else {
    Write-Output ("RAM size  : {0} bytes (from -RamBytes)" -f $RamBytes)
}

$WORDS = $RamBytes / $SYMS     # lines per symbol file

if (-not (Test-Path $Bin)) {
    Write-Output ("!! firmware binary not found: " + $Bin)
    Write-Output "   build it first:  powershell -File build_sw.ps1"
    exit 1
}

$fw = [System.IO.File]::ReadAllBytes($Bin)
Write-Output ("firmware : {0}  ({1} bytes)" -f $Bin, $fw.Length)
if ($fw.Length -gt $RamBytes) {
    Write-Output ("!! firmware is {0} bytes but the SoC RAM is only {1} bytes -- it will NOT fit." -f $fw.Length, $RamBytes)
    exit 2
}
Write-Output ("RAM      : {0} bytes, {1} used, {2} free" -f $RamBytes, $fw.Length, ($RamBytes - $fw.Length))

if (-not (Test-Path $OutDir)) { New-Item -ItemType Directory -Path $OutDir -Force | Out-Null }

# ---- build the 4 symbol files ----
# symbolN[i] = byte at address (4*i + N);  absent bytes read as 0
$sb = New-Object 'System.Text.StringBuilder[]' $SYMS
for ($n = 0; $n -lt $SYMS; $n++) { $sb[$n] = New-Object System.Text.StringBuilder }

$bits = New-Object 'string[]' 256
for ($v = 0; $v -lt 256; $v++) {
    $s = ''
    for ($b = 7; $b -ge 0; $b--) { $s += $(if (($v -shr $b) -band 1) { '1' } else { '0' }) }
    $bits[$v] = $s
}

for ($i = 0; $i -lt $WORDS; $i++) {
    for ($n = 0; $n -lt $SYMS; $n++) {
        $a = 4 * $i + $n
        $byte = if ($a -lt $fw.Length) { $fw[$a] } else { 0 }
        [void]$sb[$n].Append($bits[$byte]).Append("`n")
    }
}

$names = @()
for ($n = 0; $n -lt $SYMS; $n++) {
    $name = "EfxSapphireSoc.v_toplevel_system_ramA_logic_ram_symbol$n.bin"
    $names += $name
    $p = Join-Path $OutDir $name
    # LF only, ASCII, no BOM -- exactly like the vendor files
    [System.IO.File]::WriteAllText($p, $sb[$n].ToString(), (New-Object System.Text.ASCIIEncoding))
    Write-Output ("wrote    : {0}  ({1} bytes)" -f $p, (Get-Item $p).Length)
}

# ---- verify by decoding back ----
$bad = 0
$dec = New-Object 'byte[]' $RamBytes
for ($n = 0; $n -lt $SYMS; $n++) {
    $lines = [System.IO.File]::ReadAllLines((Join-Path $OutDir $names[$n]))
    if ($lines.Count -ne $WORDS) { Write-Output ("!! symbol{0}: {1} lines, expected {2}" -f $n, $lines.Count, $WORDS); $bad++; continue }
    for ($i = 0; $i -lt $WORDS; $i++) {
        if ($lines[$i].Length -ne 8) { $bad++; continue }
        $dec[4 * $i + $n] = [Convert]::ToByte($lines[$i], 2)
    }
}
for ($k = 0; $k -lt $fw.Length; $k++) { if ($dec[$k] -ne $fw[$k]) { $bad++ } }
for ($k = $fw.Length; $k -lt $RamBytes; $k++) { if ($dec[$k] -ne 0) { $bad++ } }

if ($bad -eq 0) {
    Write-Output ("round-trip verify : OK (all {0} bytes decode back identically)" -f $RamBytes)
} else {
    Write-Output ("round-trip verify : {0} MISMATCHES" -f $bad)
    exit 3
}

# ---- sanity: show the first few instructions so the entry point is visible ----
Write-Output "first 3 words (should be valid RISC-V, and any absolute address should be 0xF9000xxx):"
for ($i = 0; $i -lt 3; $i++) {
    $w = [int64]$dec[4*$i] + [int64]$dec[4*$i+1]*256 + [int64]$dec[4*$i+2]*65536 + [int64]$dec[4*$i+3]*16777216
    Write-Output ("   [{0}] 0x{1:X8}" -f $i, $w)
}

if ($Install) {
    if (-not (Test-Path $IpDir)) { Write-Output ("!! IP dir not found: " + $IpDir); exit 4 }
    # ★ 有两份副本，必须都换：IP 根目录那份是 mmt.xml 引用的 sapphire_soc.v 用
    #   $readmemb 相对路径加载的（构建脚本给了 --I ip/sapphire_soc），
    #   source\hardware\netlist 下那份是 IP 再生成时的原始位置。
    #   只换一处会出现"明明换了固件但烧进去还是旧的"这种极难查的问题。
    $targets = @($IpDir, (Join-Path $IpDir 'source\hardware\netlist'))
    foreach ($t in $targets) {
        if (-not (Test-Path $t)) { Write-Output ("   skip (not present): " + $t); continue }
        foreach ($name in $names) {
            Copy-Item (Join-Path $OutDir $name) (Join-Path $t $name) -Force
        }
        Write-Output ("installed into : " + $t)
    }
    Write-Output "   (back up the vendor image first if you have not: they are overwritten)"
    Write-Output "   (then re-run the Efinity build so the new RAM init is picked up)"
}
